import type { LayoutIssue } from '@busverse/seat-engine';
import { errors } from '../../lib/errors.js';

export const networkErrors = {
  busNotFound: () => errors.notFound('Bus not found'),
  routeNotFound: () => errors.notFound('Route not found'),
  scheduleNotFound: () => errors.notFound('Schedule not found'),
  cityNotFound: () => errors.notFound('City not found'),
  standNotFound: () => errors.notFound('Stand not found'),
  layoutNotFound: () => errors.notFound('Seat layout not found'),
  driverNotFound: () => errors.notFound('Driver not found'),
  bookingNotFound: () => errors.notFound('Booking not found'),
  layoutHasBookings: () => errors.invalidRequest('Cannot modify seat layout of a bus with existing bookings'),
  layoutInvalid: (issues: readonly LayoutIssue[]) => errors.invalidRequest(issues[0]?.message ?? 'Invalid seat layout', { issues }),
  layoutInUse: (conflicts: readonly unknown[]) => errors.layoutInUse({ conflicts }),
  invalidSeatCoordinates: (d?: string) => errors.invalidRequest(d ?? 'Invalid seat coordinates'),
  duplicateSeatCoordinates: (label: string) => errors.invalidRequest(`Duplicate seat at ${label}`),
  busNotApproved: () => errors.invalidRequest('Bus is not approved'),
  routeNotApproved: () => errors.invalidRequest('Route is not approved'),
  capacityMismatch: (seats: number, capacity: number) => errors.invalidRequest(`Seat count (${seats}) does not match bus capacity (${capacity})`),
  routeSameCity: () => errors.invalidRequest('Origin and destination cities must differ'),
  routeStandsInsufficient: () => errors.invalidRequest('Route must have at least 2 stands'),
  routeStandSequenceInvalid: (detail: string) => errors.invalidRequest(`Invalid stand sequence: ${detail}`),
  routeStandCityMismatch: (detail: string) => errors.invalidRequest(`Stand city mismatch: ${detail}`),
  routeStandDuplicate: () => errors.invalidRequest('Duplicate stand in route'),
  routeHasSchedules: (count: number) => errors.routeInUse(count),
  scheduleTimeInvalid: () => errors.invalidRequest('Arrival must be after departure'),
  scheduleBusConflict: (conflictId: string, departureTime: string, arrivalTime: string) =>
    errors.scheduleConflict(conflictId, departureTime, arrivalTime),
  scheduleNotDraft: () => errors.invalidRequest('Only DRAFT schedules can be modified'),
  scheduleBusNotApproved: () => errors.invalidRequest('Bus must be APPROVED before publishing'),
  scheduleRouteNotApproved: () => errors.invalidRequest('Route must be APPROVED before publishing'),
  scheduleAlreadyPublished: () => errors.invalidRequest('Schedule is already published'),
  driverAlreadyInvited: () => errors.invalidRequest('Driver already invited by this operator'),
  driverBelongsToOtherOperator: () => errors.invalidRequest('Driver belongs to another operator'),
  driverOnDuty: () => errors.driverOnDuty(),
  driverKycNotVerified: () => errors.driverNotVerified(),
  notOwnerOnly: () => errors.forbidden('Only the operator owner can access this'),
};
